package main

// Database GUI: Adminer (one PHP file, Apache-2.0/GPL-2.0) served by PHP's built-in server on 127.0.0.1,
// so it works whatever the web server is (Apache, Nginx, or Herd's).

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"sync"
	"time"
)

const (
	adminerURL = "https://github.com/vrana/adminer/releases/download/v6.3.0/adminer-6.3.0.php"
	adminerSHA = "641e1a31e8cc333a309e202ef9446e1fd38c2069ed5f9ee509b80d70089d0503"
)

// adminerIndex allows logging in without a password (Laragon's MySQL root and PostgreSQL's postgres have
// none). The database still checks the credentials; the server only listens on 127.0.0.1.
const adminerIndex = `<?php
// Generated by DevPanel.
function adminer_object() {
    class DevPanelAdminer extends Adminer\Adminer {
        function name() { return 'DevPanel · Adminer'; }
        function login($login, $password) { return true; }
    }
    return new DevPanelAdminer;
}
include __DIR__ . '/adminer.php';
`

var adminer struct {
	sync.Mutex
	cmd *exec.Cmd
}

func (a *App) adminerDir() string { return a.path(`bin\adminer`) }

// ensureAdminer downloads Adminer once (checked against its SHA-256) and writes the index wrapper.
func (a *App) ensureAdminer() error {
	dir := a.adminerDir()
	f := filepath.Join(dir, "adminer.php")
	if !exists(f) {
		tmp, err := a.download("adminer", adminerURL)
		if err != nil {
			return fmt.Errorf("adminer: %w", err)
		}
		defer os.Remove(tmp)
		if got, _ := fileSHA256(tmp); !strings.EqualFold(got, adminerSHA) {
			return errors.New("adminer checksum mismatch; nothing installed")
		}
		b, err := os.ReadFile(tmp)
		if err != nil {
			return err
		}
		os.MkdirAll(dir, 0755)
		if err := os.WriteFile(f, b, 0644); err != nil {
			return err
		}
	}
	_, err := writeIfChanged(filepath.Join(dir, "index.php"), adminerIndex)
	return err
}

// OpenAdminer starts Adminer if needed and returns its URL, pre-filled for engine ("mysql" or "postgresql").
func (a *App) OpenAdminer(engine string) (string, error) {
	if err := a.ensureAdminer(); err != nil {
		return "", err
	}
	p := port("adminer")
	adminer.Lock()
	defer adminer.Unlock()
	if adminer.cmd == nil || !portOpen(p) {
		if portOpen(p) {
			return "", fmt.Errorf("port %d is used by %s (change it in Settings → Ports)", p, a.portOwner(p))
		}
		php := a.svcDir("php")
		if php == "" {
			return "", errors.New("no PHP installed")
		}
		cmd := hidden(exec.Command(filepath.Join(php, "php.exe"), "-S", "127.0.0.1:"+strconv.Itoa(p), "-t", a.adminerDir()))
		cmd.Dir = a.adminerDir()
		cmd.Env = append(os.Environ(), "PATH="+phpEnvPath(php))
		if err := cmd.Start(); err != nil {
			return "", err
		}
		go cmd.Wait()
		adminer.cmd = cmd
		for i := 0; i < 50 && !portOpen(p); i++ {
			time.Sleep(100 * time.Millisecond)
		}
		if !portOpen(p) {
			cmd.Process.Kill()
			adminer.cmd = nil
			return "", errors.New("adminer did not start (does this PHP have mysqli / pdo_pgsql enabled?)")
		}
	}
	u := fmt.Sprintf("http://127.0.0.1:%d/", p)
	switch engine {
	case "mysql":
		u += fmt.Sprintf("?server=127.0.0.1:%d&username=root", port("mysql"))
	case "postgresql":
		u += fmt.Sprintf("?pgsql=127.0.0.1:%d&username=postgres", port("postgresql"))
	}
	return u, nil
}

// StopAdminer ends the Adminer server (only the process DevPanel started).
func (a *App) StopAdminer() {
	adminer.Lock()
	defer adminer.Unlock()
	if adminer.cmd != nil && adminer.cmd.Process != nil {
		adminer.cmd.Process.Kill()
		for i := 0; i < 30 && portOpen(port("adminer")); i++ { // the socket closes a moment after the process
			time.Sleep(100 * time.Millisecond)
		}
	}
	adminer.cmd = nil
}
