// ---- PHP per site (#8) ----

// SetSitePHP pins a PHP version for one site ("" = the default PHP).
func (a *App) SetSitePHP(folder, version string) error {
	a.mu.Lock()
	defer a.mu.Unlock()
	if _, err := a.siteDir(folder); err != nil {
		return err
	}
	if version != "" && !slices.Contains(a.PHPVersions(), version) {
		return fmt.Errorf("PHP %q is not installed", version)
	}
	if a.cfg.SitePHP == nil {
		a.cfg.SitePHP = map[string]string{}
	}
	if version == "" || version == a.CurrentPHP() {
		delete(a.cfg.SitePHP, folder)
	} else {
		a.cfg.SitePHP[folder] = version
	}
	if _, _, err := a.syncVhostFiles(); err != nil {
		return err
	}
	if err := a.saveConfig(); err != nil {
		return err
	}
	return a.restartWeb()
}

func (a *App) phpDir(version string) string { return a.path(`bin\php\` + version) }

// phpEnvPath is the PATH a php-cgi needs: its own dir first so ext DLL dependencies (libpq, icu...) match.
func phpEnvPath(dir string) string {
	return dir + `;C:\Windows\system32;C:\Windows;C:\Windows\System32\Wbem`
}

// apachePHPConf renders etc\apache2\devpanel-php.conf: one FcgidCmdOptions per extra PHP version (own php.ini
// and DLL path) and a <Directory> override per site. It's included after fcgid.conf, where mod_fcgid exists.
func (a *App) apachePHPConf(list []Site) string {
	fwd := filepath.ToSlash
	var b strings.Builder
	b.WriteString("# Generated by DevPanel: PHP version per site. Do not edit.\n<IfModule fcgid_module>\n")
	var versions []string
	for _, s := range list {
		if s.PHP != "" && !slices.Contains(versions, s.PHP) {
			versions = append(versions, s.PHP)
		}
	}
	slices.Sort(versions)
	for _, v := range versions {
		d := a.phpDir(v)
		fmt.Fprintf(&b, "FcgidCmdOptions \"%s\" InitialEnv PHPRC=\"%s\" InitialEnv PATH=\"%s\" InitialEnv PHP_FCGI_MAX_REQUESTS=0 IOTimeout 36000\n",
			fwd(filepath.Join(d, "php-cgi.exe")), fwd(d), fwd(phpEnvPath(d)))
	}
	for _, s := range list {
		if s.PHP == "" {
			continue
		}
		fmt.Fprintf(&b, "<Directory \"%s\">\n    <Files ~ \"\\.php$\">\n        FcgidWrapper \"%s\" .php\n    </Files>\n</Directory>\n",
			fwd(s.Root), fwd(filepath.Join(a.phpDir(s.PHP), "php-cgi.exe")))
	}
	b.WriteString("</IfModule>\n")
	return b.String()
}

var includeLine = regexp.MustCompile(`(?m)^IncludeOptional\s+"?[^"\r\n]*devpanel-php\.conf"?\s*$`)

// ensureApacheInclude adds the devpanel-php.conf include to httpd.conf once, after the fcgid include.
func (a *App) ensureApacheInclude() error {
	f := filepath.Join(a.svcDir("apache"), `conf\httpd.conf`)
	b, err := os.ReadFile(f)
	if err != nil {
		return nil // Apache not installed
	}
	if includeLine.Match(b) {
		return nil
	}
	line := `IncludeOptional "` + filepath.ToSlash(a.path(`etc\apache2\devpanel-php.conf`)) + `"`
	s := string(b)
	if !strings.HasSuffix(s, "\n") {
		s += "\r\n"
	}
	return os.WriteFile(f, []byte(s+line+"\r\n"), 0644)
}

// ---- Nginx (#7) ----

const poolSize = 3 // php-cgi processes per PHP version (each handles one request at a time)

func (a *App) nginxConfPath() string { return a.path(`etc\nginx\devpanel-nginx.conf`) }
func (a *App) phpPidsPath() string   { return a.path(`etc\nginx\devpanel-phpcgi.pids`) }

// phpPools maps each PHP version used by Nginx sites to its FastCGI ports.
func (a *App) phpPools(list []Site) (versions []string, ports map[string][]int) {
	versions = []string{a.CurrentPHP()}
	for _, s := range list {
		if s.PHP != "" && !slices.Contains(versions, s.PHP) {
			versions = append(versions, s.PHP)
		}
	}
	ports = map[string][]int{}
	base := port("php_fastcgi")
	for i, v := range versions {
		for k := 0; k < poolSize; k++ {
			ports[v] = append(ports[v], base+i*10+k)
		}
	}
	return versions, ports
}

func upstreamName(v string) string {
	return "php_" + regexp.MustCompile(`[^a-z0-9]+`).ReplaceAllString(strings.ToLower(v), "_")
}

func (a *App) nginxConf(list []Site) string {
	fwd := filepath.ToSlash
	nd := a.svcDir("nginx")
	_, _, crt, key := a.sslFiles()
	versions, pools := a.phpPools(list)
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by DevPanel. Do not edit; change sites in DevPanel.
worker_processes 1;
error_log logs/error.log;
pid logs/nginx.pid;
events { worker_connections 1024; }
http {
    include "%s";
    default_type application/octet-stream;
    sendfile on;
    keepalive_timeout 65;
    client_max_body_size 2G;
    fastcgi_read_timeout 36000;
    server_names_hash_bucket_size 256;
    server_names_hash_max_size 4096;
    access_log logs/access.log;
`, fwd(filepath.Join(nd, `conf\mime.types`)))
	for _, v := range versions {
		fmt.Fprintf(&b, "    upstream %s {\n", upstreamName(v))
		for _, p := range pools[v] {
			fmt.Fprintf(&b, "        server 127.0.0.1:%d;\n", p)
		}
		b.WriteString("    }\n")
	}
	fcgi := fwd(filepath.Join(nd, `conf\fastcgi_params`))
	def := upstreamName(a.CurrentPHP())
	// Default server: localhost, plus Laragon's Apache aliases (/phpmyadmin, ...) whose folders exist.
	fmt.Fprintf(&b, `    server {
        listen %d default_server;
        listen %d ssl default_server;
        server_name localhost;
        root "%s";
        index index.php index.html index.htm;
        ssl_certificate "%s";
        ssl_certificate_key "%s";
        autoindex on;
`, port("nginx"), port("nginx_ssl"), fwd(a.www()), fwd(crt), fwd(key))
	for _, al := range a.webAliases() {
		fmt.Fprintf(&b, `        location = %[1]s { return 301 %[1]s/; }
        location ^~ %[1]s/ {
            alias "%[2]s/";
            index index.php index.html;
            location ~ \.php$ {
                include "%[3]s";
                fastcgi_param SCRIPT_FILENAME $request_filename;
                fastcgi_pass %[4]s;
            }
        }
`, al[0], al[1], fcgi, def)
	}
	fmt.Fprintf(&b, `        location ~ \.php$ {
            try_files $uri =404;
            include "%s";
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_pass %s;
        }
    }
`, fcgi, def)
	tpl := userTpl(a.nginxTplPath(), nginxTplDefault)
	for _, s := range list {
		names := []string{s.Host, "*." + s.Host}
		for _, al := range s.Aliases {
			names = append(names, al, "*."+al)
		}
		php := s.PHP
		if php == "" {
			php = a.CurrentPHP()
		}
		b.WriteString(fillTpl(tpl, map[string]string{"NAMES": strings.Join(names, " "), "ROOT": fwd(s.Root),
			"HTTP_PORT": strconv.Itoa(port("nginx")), "SSL_PORT": strconv.Itoa(port("nginx_ssl")), "CERT": fwd(crt), "KEY": fwd(key),
			"FASTCGI_PARAMS": fcgi, "UPSTREAM": upstreamName(php), "LOCATIONS": nginxLocations(a.cfg.SiteProxy[s.Folder], fcgi, upstreamName(php))}))
	}
	b.WriteString("}\n")
	return b.String()
}

func writeIfChanged(f, content string) (bool, error) {
	if old, err := os.ReadFile(f); err == nil && string(old) == content {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(f), 0755); err != nil {
		return false, err
	}
	return true, os.WriteFile(f, []byte(content), 0644)
}

// writeNginxConf writes the Nginx config; returns true if it changed. No-op when Nginx isn't installed.
func (a *App) writeNginxConf(list []Site) (bool, error) {
	if a.svcDir("nginx") == "" {
		return false, nil
	}
	return writeIfChanged(a.nginxConfPath(), a.nginxConf(list))
}

// startPHPPools spawns php-cgi FastCGI listeners for Nginx and records their PIDs.
func (a *App) startPHPPools(list []Site) error {
	versions, pools := a.phpPools(list)
	var pids []string
	for _, v := range versions {
		d := a.phpDir(v)
		for _, p := range pools[v] {
			if portOpen(p) {
				return fmt.Errorf("FastCGI port %d is already in use", p)
			}
			cmd := exec.Command(filepath.Join(d, "php-cgi.exe"), "-b", fmt.Sprintf("127.0.0.1:%d", p))
			cmd.Dir = d
			cmd.Env = append(os.Environ(), "PHPRC="+d, "PATH="+phpEnvPath(d), "PHP_FCGI_MAX_REQUESTS=0")
			cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true, CreationFlags: 0x08000000}
			if err := cmd.Start(); err != nil {
				a.stopPHPPools()
				return fmt.Errorf("php-cgi %s: %w", v, err)
			}
			go cmd.Wait()
			pids = append(pids, strconv.Itoa(cmd.Process.Pid))
			os.WriteFile(a.phpPidsPath(), []byte(strings.Join(pids, "\n")), 0644)
		}
	}
	// Wait until every php-cgi listens: a web server that starts faster would answer 502 meanwhile,
	// and a php-cgi that can't start (bad php.ini, missing DLL) should be reported, not hidden.
	for _, v := range versions {
		for _, p := range pools[v] {
			if !waitPort(p, true, 10*time.Second) {
				a.stopPHPPools()
				return fmt.Errorf("php-cgi %s did not start on port %d (check its php.ini / extensions)", v, p)
			}
		}
	}
	return nil
}

// stopPHPPools kills the recorded php-cgi PIDs (only if they still are php-cgi.exe processes).
func (a *App) stopPHPPools() {
	b, _ := os.ReadFile(a.phpPidsPath())
	for _, l := range strings.Fields(string(b)) {
		pid, err := strconv.Atoi(l)
		if err != nil || !strings.EqualFold(filepath.Base(exePath(uint32(pid))), "php-cgi.exe") {
			continue
		}
		if p, err := os.FindProcess(pid); err == nil {
			p.Kill()
		}
	}
	os.Remove(a.phpPidsPath())
}

func (a *App) startNginx() error {
	nd := a.svcDir("nginx")
	list, _ := a.sites()
	if _, err := a.writeLeaf(allHosts(list)); err != nil { // listen ... ssl needs the certificate
		return err
	}
	if _, err := a.writeNginxConf(list); err != nil {
		return err
	}
	for _, d := range []string{"logs", `temp\client_body_temp`, `temp\proxy_temp`, `temp\fastcgi_temp`, `temp\uwsgi_temp`, `temp\scgi_temp`} {
		os.MkdirAll(filepath.Join(nd, d), 0755)
	}
	if out, err := output(filepath.Join(nd, "nginx.exe"), "-t", "-p", nd, "-c", a.nginxConfPath()); err != nil || !strings.Contains(out, "successful") {
		return fmt.Errorf("nginx config test failed: %s", out)
	}
	if err := a.startPHPPools(list); err != nil {
		return err
	}
	if err := spawn(filepath.Join(nd, "nginx.exe"), "-p", nd, "-c", a.nginxConfPath()); err != nil {
		a.stopPHPPools()
		return err
	}
	return nil
}

func (a *App) stopNginx() {
	nd := a.svcDir("nginx")
	run(filepath.Join(nd, "nginx.exe"), "-p", nd, "-c", a.nginxConfPath(), "-s", "quit")
	for end := time.Now().Add(5 * time.Second); time.Now().Before(end) && len(processesUnder(nd)) > 0; time.Sleep(200 * time.Millisecond) {
	}
	killUnder(nd)
	a.stopPHPPools()
}

// restartWeb restarts whichever of Apache / Nginx is running from this install.
func (a *App) restartWeb() error {
	var errs []error
	if a.running("nginx") {
		// Test the regenerated config before stopping, so a broken template keeps Nginx up.
		list, _ := a.sites()
		nd := a.svcDir("nginx")
		a.writeNginxConf(list)
		if out, err := output(filepath.Join(nd, "nginx.exe"), "-t", "-p", nd, "-c", a.nginxConfPath()); err != nil || !strings.Contains(out, "successful") {
			errs = append(errs, fmt.Errorf("nginx config error, kept the running Nginx unchanged: %s", out))
		} else {
			a.stopNginx()
			errs = append(errs, a.start("nginx"))
		}
	}
	for _, w := range []string{"caddy", "frankenphp"} {
		if !a.running(w) {
			continue
		}
		list, _ := a.sites()
		a.writeCaddyConf(w, list)
		if err := a.validateCaddy(w); err != nil {
			errs = append(errs, fmt.Errorf("%w; kept the running %s unchanged", err, w))
			continue
		}
		a.stopExtra(w)
		errs = append(errs, a.start(w))
	}
	return errors.Join(append(errs, a.restartApache())...)
}
