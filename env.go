type EnvItem struct {
	Name     string   `json:"name"`
	Label    string   `json:"label"`
	Version  string   `json:"version"`
	Versions []string `json:"versions"`
	Service  bool     `json:"service"`
	Running  bool     `json:"running"`
	Enabled  bool     `json:"enabled"` // runtimes always; services when ticked
	Category string   `json:"category"`
}

func (a *App) Environment() []EnvItem {
	out := []EnvItem{}
	for _, t := range envTools {
		it := EnvItem{Name: t.Name, Label: t.Label, Versions: a.versions(t.Name), Enabled: svc(t.Name).Name == "" || a.enabled(t.Name), Category: categoryOf(t.Name)}
		if t.Name == "php" {
			it.Versions, it.Version = a.PHPVersions(), a.CurrentPHP()
		} else if d := a.svcDir(t.Name); d != "" {
			it.Version = filepath.Base(d)
		}
		if s := svc(t.Name); s.Name != "" {
			it.Service, it.Running = true, a.running(t.Name)
		}
		out = append(out, it)
	}
	return out
}

func (a *App) toolPaths(name string, sub []string) []string {
	d := a.svcDir(name)
	if d == "" {
		return nil
	}
	var out []string
	for _, p := range sub {
		out = append(out, filepath.Join(d, p))
	}
	return out
}

func (a *App) envCmdPath() string { return a.path(`usr\devpanel-env.cmd`) }

// envPaths are the selected versions' dirs plus Composer/Git, to put first on PATH.
func (a *App) envPaths() []string {
	var p []string
	for _, t := range envTools {
		p = append(p, a.toolPaths(t.Name, t.Paths)...)
	}
	return append(p, a.path(`bin\composer`), a.path(`bin\git\cmd`), a.path(`usr\bin`))
}

// writeEnvCmd writes a cmd script that puts the selected versions first on PATH (like Laragon's terminal).
func (a *App) writeEnvCmd() error {
	p := a.envPaths()
	s := "@echo off\r\n:: Generated by DevPanel. Selected environment versions first on PATH.\r\n"
	for _, kv := range a.runtimeEnv() {
		s += "SET \"" + kv + "\"\r\n"
	}
	s +=
		"SET \"PATH=" + strings.Join(p, ";") + ";%PATH%\"\r\n"
	return os.WriteFile(a.envCmdPath(), []byte(s), 0644)
}

func (a *App) OpenTerminal() error {
	if err := a.writeEnvCmd(); err != nil {
		return err
	}
	// `start ""` = empty window title; /D sets the working dir.
	return a.openConsole(a.www())
}

// rewritePath replaces every C:\laragon\bin\<tool>\... entry with the selected version's dirs,
// in the same position. A tool not on PATH yet is appended only if explicitly selected.
func (a *App) rewritePath(old string) string {
	var parts []string
	for _, p := range strings.Split(old, ";") {
		if strings.TrimSpace(p) != "" {
			parts = append(parts, p)
		}
	}
	bin := strings.ToLower(a.path("bin")) + `\`
	for _, t := range envTools {
		if !t.UserPath {
			continue
		}
		prefix := bin + t.Name + `\`
		idx, kept := -1, []string{}
		for _, p := range parts {
			if strings.HasPrefix(strings.ToLower(p), prefix) {
				if idx < 0 {
					idx = len(kept)
				}
				continue
			}
			kept = append(kept, p)
		}
		want := a.toolPaths(t.Name, t.Paths)
		if idx < 0 {
			if a.cfg.Versions[t.Name] == "" || len(want) == 0 {
				continue
			}
			idx = len(kept)
		}
		parts = append(kept[:idx], append(want, kept[idx:]...)...)
	}
	return strings.Join(parts, ";")
}

// ApplyUserPath writes the selected versions into the Windows user PATH (HKCU, no admin needed).
// The previous value is saved next to devpanel.json first.
func (a *App) ApplyUserPath() (string, error) {
	a.mu.Lock()
	defer a.mu.Unlock()
	k, err := registry.OpenKey(registry.CURRENT_USER, "Environment", registry.QUERY_VALUE|registry.SET_VALUE)
	if err != nil {
		return "", err
	}
	defer k.Close()
	old, typ, err := k.GetStringValue("Path")
	if err != nil && !errors.Is(err, registry.ErrNotExist) {
		return "", err
	}
	updated := a.rewritePath(old)
	if updated == old {
		return "user PATH already up to date", nil
	}
	backup := filepath.Join(filepath.Dir(a.cfgPath), "path-backup-"+time.Now().Format("20060102-150405")+".txt")
	if err := os.WriteFile(backup, []byte(old), 0644); err != nil {
		return "", fmt.Errorf("could not back up PATH, nothing changed: %w", err)
	}
	if typ == registry.EXPAND_SZ {
		err = k.SetExpandStringValue("Path", updated)
	} else {
		err = k.SetStringValue("Path", updated)
	}
	if err != nil {
		return "", err
	}
	// Tell Explorer and new terminals that the environment changed.
	env, _ := windows.UTF16PtrFromString("Environment")
	windows.NewLazySystemDLL("user32.dll").NewProc("SendMessageTimeoutW").
		Call(0xffff, 0x001A, 0, uintptr(unsafe.Pointer(env)), 0x0002, 5000, 0)
	return "user PATH updated (backup: " + backup + "). Open a new terminal to use it.", nil
}
