// detectRoot: next to a Laragon install (…\laragon\devpanel\devpanel.exe) use Laragon's folder,
// otherwise DevPanel's own folder (C:\devpanel\bin, \www, \data, \etc ...).
func detectRoot(exeDir string) string {
	parent := filepath.Dir(exeDir)
	if exists(filepath.Join(parent, "laragon.exe")) || exists(filepath.Join(parent, `etc\apache2\sites-enabled`)) {
		return parent
	}
	return exeDir
}

// Standalone is true when DevPanel runs without a Laragon installation.
func (a *App) Standalone() bool { return !exists(a.path("laragon.exe")) }

// ensureLayout creates DevPanel's folders.
func (a *App) ensureLayout() {
	for _, d := range []string{"bin", "data", "www", "usr", "backup", `etc\apache2\sites-enabled`, `etc\apache2\alias`, `etc\apache2\modules`,
		`etc\nginx`, `etc\caddy`, `etc\ssl`, `etc\apps`} {
		os.MkdirAll(a.path(d), 0755)
	}
}

// Official download for mod_fcgid (PHP for Apache); Laragon ships its own copy.
var modFcgidURL = "https://www.apachelounge.com/download/VS18/modules/mod_fcgid-2.3.10-win64-VS18.zip"

func (a *App) fcgidModule() string { return a.path(`etc\apache2\modules\mod_fcgid.so`) }

// ensureFcgidModule downloads mod_fcgid.so if missing.
func (a *App) ensureFcgidModule() error {
	if exists(a.fcgidModule()) {
		return nil
	}
	f, err := a.download("mod_fcgid", modFcgidURL)
	if err != nil {
		return fmt.Errorf("mod_fcgid: %w", err)
	}
	defer os.Remove(f)
	tmp, err := os.MkdirTemp("", "devpanel-fcgid-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	if err := extract(f, filepath.Join(tmp, "x")); err != nil {
		return err
	}
	so := findExe(tmp, "mod_fcgid.so")
	if so == "" {
		return errors.New("mod_fcgid.so not found in the download")
	}
	b, err := os.ReadFile(so)
	if err != nil {
		return err
	}
	os.MkdirAll(filepath.Dir(a.fcgidModule()), 0755)
	return os.WriteFile(a.fcgidModule(), b, 0644)
}

// writeFcgidConf points Apache's PHP handler at a PHP folder (same layout Laragon writes).
func (a *App) writeFcgidConf(phpVersion string) error {
	fwd := filepath.ToSlash
	d := fwd(a.phpDir(phpVersion))
	conf := fmt.Sprintf(`LoadModule fcgid_module "%[1]s"

<IfModule fcgid_module>
FcgidInitialEnv PATH "%[2]s;C:/Windows/system32;C:/Windows;C:/Windows/System32/Wbem;"
FcgidInitialEnv SystemRoot "C:/Windows"
FcgidInitialEnv SystemDrive "C:"
FcgidInitialEnv TEMP "C:/Windows/Temp"
FcgidInitialEnv TMP "C:/Windows/Temp"
FcgidInitialEnv windir "C:/Windows"
FcgidIOTimeout 36000
FcgidConnectTimeout 16
FcgidMaxRequestsPerProcess 0
FcgidMaxProcesses 50
FcgidMaxRequestLen 81310720
FcgidInitialEnv PHPRC "%[2]s"
FcgidInitialEnv PHP_FCGI_MAX_REQUESTS 0

<Files ~ "\.php$">
AddHandler fcgid-script .php
Options +ExecCGI
FcgidWrapper "%[2]s/php-cgi.exe" .php
</Files>
</IfModule>
`, fwd(a.fcgidModule()), d)
	_, err := writeIfChanged(a.path(`etc\apache2\fcgid.conf`), conf)
	return err
}

