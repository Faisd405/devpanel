// ngrokExe finds ngrok in Laragon's place (bin\ngrok\ngrok.exe) or in an installed version folder.
func (a *App) ngrokExe() string {
	if p := a.path(`bin\ngrok\ngrok.exe`); exists(p) {
		return p
	}
	return findExe(a.path(`bin\ngrok`), "ngrok.exe")
}
