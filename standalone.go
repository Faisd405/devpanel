// ensureApacheConfig makes a freshly installed (stock) Apache work with DevPanel. An httpd.conf that already
// includes sites-enabled (Laragon's or DevPanel's) is left alone; a stock one is replaced and kept as httpd.conf.dist.
func (a *App) ensureApacheConfig(dir string) error {
	f := filepath.Join(dir, `conf\httpd.conf`)
	b, err := os.ReadFile(f)
	if err != nil {
		return fmt.Errorf("apache: %w", err)
	}
	fwd := filepath.ToSlash
	_, _, crt, key := a.sslFiles()
	vals := map[string]string{"SRV": fwd(dir), "PORT": strconv.Itoa(port("apache")), "SSLPORT": strconv.Itoa(port("apache_ssl")),
		"WWW": fwd(a.www()), "ETC": fwd(a.path(`etc\apache2`)), "CERT": fwd(crt), "KEY": fwd(key)}
	if !strings.Contains(string(b), "sites-enabled") {
		dist := f + ".dist"
		if !exists(dist) {
			os.WriteFile(dist, b, 0644)
		}
		if err := os.WriteFile(f, []byte(fillTpl(standaloneHttpdConf, vals)), 0644); err != nil {
			return err
		}
	}
	a.ensureLayout()
	if !exists(a.path(`etc\apache2\httpd-ssl.conf`)) {
		os.WriteFile(a.path(`etc\apache2\httpd-ssl.conf`), []byte(fillTpl(standaloneSSLConf, vals)), 0644)
	}
	if !exists(a.path(`etc\apache2\sites-enabled\00-default.conf`)) {
		if _, err := a.writeLeaf(nil); err != nil { // the default vhost needs a certificate
			return err
		}
		os.WriteFile(a.path(`etc\apache2\sites-enabled\00-default.conf`), []byte(fillTpl(standaloneDefaultVhost, vals)), 0644)
	}
	if !exists(a.path(`etc\apache2\fcgid.conf`)) {
		php := a.CurrentPHP()
		if php == "" {
			return nil // no PHP yet: Apache serves static files; fcgid.conf is written when PHP gets installed
		}
		if err := a.writeFcgidConf(php); err != nil {
			return err
		}
	}
	return a.ensureFcgidModule()
}

// ensurePhpMyAdminAlias adds /phpmyadmin for a phpMyAdmin installed into etc\apps (Laragon ships its own alias file).
func (a *App) ensurePhpMyAdminAlias() error {
	dir := a.path(`etc\apps\phpMyAdmin`)
	f := a.path(`etc\apache2\alias\phpmyadmin.conf`)
	if !exists(dir) || exists(f) {
		return nil
	}
	d := filepath.ToSlash(dir) + "/"
	conf := "Alias /phpmyadmin \"" + d + "\"\n\n<Directory \"" + d + "\">\n    AllowOverride All\n    Require local\n</Directory>\n"
	os.MkdirAll(filepath.Dir(f), 0755)
	return os.WriteFile(f, []byte(conf), 0644)
}

// OnlinePackages fetches installable versions from the official feeds (PHP: newest of each 7.4-8.x line,
// Node: newest), for installs without Laragon's catalog. Called on request, never in the background.
func (a *App) OnlinePackages(name string) []Package {
	if name != "php" && name != "nodejs" {
		return []Package{}
	}
	onlineLookup(a, name, "")
	return a.PackagesFor(name)
}

// ---- Composer ----

var composerURL = "https://getcomposer.org/download/latest-stable/composer.phar"

func (a *App) composerPhar() string { return a.path(`bin\composer\composer.phar`) }

// ensureComposer downloads composer.phar (SHA-256 checked) and a composer.bat wrapper when missing.
func (a *App) ensureComposer() error {
	phar := a.composerPhar()
	if !exists(phar) {
		f, err := a.download("composer", composerURL)
		if err != nil {
			return fmt.Errorf("composer: %w", err)
		}
		defer os.Remove(f)
		if sum, err := httpGet(composerURL+".sha256sum", 4096); err == nil {
			want := strings.Fields(string(sum))
			got, _ := fileSHA256(f)
			if len(want) == 0 || !strings.EqualFold(want[0], got) {
				return errors.New("composer.phar checksum mismatch; nothing installed")
			}
		}
		os.MkdirAll(filepath.Dir(phar), 0755)
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		if err := os.WriteFile(phar, b, 0644); err != nil {
			return err
		}
	}
	bat := filepath.Join(filepath.Dir(phar), "composer.bat")
	if !exists(bat) {
		os.WriteFile(bat, []byte("@ECHO OFF\r\nphp \"%~dp0composer.phar\" %*\r\n"), 0644)
	}
	return nil
}

// ---- Archives with Windows' own tar (libarchive): .tar.xz, .tar.gz, .7z ----

func windowsTar() string { return filepath.Join(os.Getenv("SystemRoot"), `System32\tar.exe`) }

func tarExtract(file, dir string) error {
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	out, err := hidden(exec.Command(windowsTar(), "-xf", file, "-C", dir)).CombinedOutput()
	if err != nil {
		return fmt.Errorf("tar: %v %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

